#!/usr/bin/env python3
"""Independent contract encoder and hash oracle. Never imports production Planar code.
Rebuild a temporary upstream C shared library, validate published upstream literals,
and reproduce the checked-in TSV. Use --check to refuse any golden drift.
"""
import argparse
import ctypes
import pathlib
import struct
import subprocess
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
class Hash(ctypes.Structure):
    _fields_ = [('low', ctypes.c_uint64), ('high', ctypes.c_uint64)]

def encode(v):
    if isinstance(v, bool):
        return bytes([int(v)])
    if isinstance(v, int):
        assert -(2**31) <= v < 2**31
        return b'\x02' + struct.pack('>q', v)
    if isinstance(v, str):
        v = v.encode('utf-8')
    if isinstance(v, bytes):
        return b'\x03' + struct.pack('>Q', len(v)) + v
    if isinstance(v, list):
        return b'\x04' + struct.pack('>Q', len(v)) + b''.join(map(encode, v))
    assert isinstance(v, dict)
    return b'\x05' + struct.pack('>Q', len(v)) + b''.join(
        encode(k) + encode(v[k]) for k in sorted(v, key=lambda s: s.encode('utf-8')))

# Hand-transcribed bytes from render-contract.md, not generated by encode().
HAND = [
    ('false', False, '00'), ('true', True, '01'),
    ('zero', 0, '020000000000000000'),
    ('negative', -1, '02ffffffffffffffff'),
    ('minimum', -(2**31), '02ffffffff80000000'),
    ('maximum', 2**31-1, '02000000007fffffff'),
    ('empty_string', b'', '030000000000000000'),
    ('raw', b'\x00\xff\x80A', '03000000000000000400ff8041'),
    ('empty_array', [], '040000000000000000'),
    ('empty_object', {}, '050000000000000000'),
    ('array', [True, False], '0400000000000000020100'),
    ('object', {'é': False, 'z': True},
     '0500000000000000020300000000000000017a01030000000000000002c3a900'),
]

def main():
    args = argparse.ArgumentParser()
    args.add_argument('--check', action='store_true')
    args = args.parse_args()
    with tempfile.TemporaryDirectory(prefix='planar-r06-oracle-') as tmp:
        lib = pathlib.Path(tmp) / 'xxhash.so'
        subprocess.run(['cc', '-shared', '-fPIC', '-O2', str(ROOT / 'vendor/xxhash/0.8.3/xxhash.c'),
                        '-o', str(lib)], check=True)
        xx = ctypes.CDLL(str(lib))
        xx.XXH3_128bits.argtypes = [ctypes.c_void_p, ctypes.c_size_t]
        xx.XXH3_128bits.restype = Hash
        def raw(data):
            h = xx.XXH3_128bits(data, len(data))
            # Explicit numeric formatting independent of canonicalFromHash.
            return f'{h.high:016x}{h.low:016x}'
        state = 2654435761
        sanity = bytearray()
        for _ in range(1025):
            sanity.append(state >> 56)
            state = state * 11400714785074694797 % 2**64
        upstream = (HERE / 'upstream-xxh3-128.tsv').read_text().splitlines()
        for row in upstream:
            n, expected = row.split('\t')
            assert raw(bytes(sanity[:int(n)])) == expected, row
        def digest(domain, value):
            return 'xxh3_128:' + raw(encode(['planar', 'canonical_v1', domain, value]))
        rows = []
        for name, value, literal in HAND:
            assert encode(value).hex() == literal, name
            rows.append(f'{name}\t{literal}\tvector_v1\t{digest("vector_v1", value)}')
        for n in [0,1,3,4,8,9,16,17,51,52,53,163,164,165,179,180,181,255,256,257,947,948,949,1024,4096]:
            value = bytes(i % 256 for i in range(n))
            rows.append(f'file_{n}\t{encode(value).hex()}\tfile_bytes_v1\t{digest("file_bytes_v1", value)}')
        # Selected normalized records, no schema/role policy implemented by native code.
        def tree(path, data):
            return [{'root':'source', 'path':path, 'kind':'file', 'mode':'0644',
                     'size':len(data), 'content':digest('file_bytes_v1', data)}]
        base_value = {'root':'source', 'label':'initial', 'entries':tree('a', b'old'), 'excluded':[]}
        base = digest('base_v1', base_value)
        current = tree('a', b'new')
        observation = {'root':'source', 'base':base, 'entries':current, 'excluded':[]}
        unit = {'work':'library', 'root':'source', 'base':base, 'paths':['a'], 'entries':current}
        unit_hash = digest('unit_output_v1', unit)
        role = {'role':'builder', 'units':[{'work':'library', 'output':unit_hash}]}
        records = [('base', 'base_v1', base_value), ('observation', 'observation_v1', observation),
                   ('unit', 'unit_output_v1', unit), ('role', 'role_output_v1', role)]
        for name, domain, value in records:
            rows.append(f'{name}\t{encode(value).hex()}\t{domain}\t{digest(domain,value)}')
        output = '\n'.join(rows) + '\n'
        target = HERE / 'canonical-v1.tsv'
        if args.check:
            assert target.read_text() == output, 'Golden mismatch'
        else:
            target.write_text(output)
        print(f'{len(HAND)} hand byte vectors; {len(upstream)} upstream hashes; {len(rows)} canonical/domain vectors verified')

if __name__ == '__main__':
    main()
